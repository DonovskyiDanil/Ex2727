// Завдання 5: Знайти та порахувати, скільки записів у колекції Messages містять слово "паровоз" (не враховуючи регістр).
db.messages.aggregate([
  { $match: { body: { $regex: /паровоз/i } } }, // Пошук слова "паровоз" без урахування регістру
  { $count: "count" } // Підрахунок знайдених документів
]);